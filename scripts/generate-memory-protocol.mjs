import fs from "node:fs"
import path from "node:path"

const root = path.resolve(import.meta.dirname, "..")
const memory = JSON.parse(fs.readFileSync(path.join(root, "src/services/agent/memory/protocol.json"), "utf8"))
const proactive = JSON.parse(fs.readFileSync(path.join(root, "src/services/proactive/protocol.json"), "utf8"))
const defs = memory.definitions

function refName(ref) {
  const normalized = ref.replace(/^memory#\//, "#/")
  return normalized.split("/").pop()
}
function tsType(spec) {
  if (spec.$ref) return refName(spec.$ref)
  if (spec.const !== undefined) return JSON.stringify(spec.const)
  if (spec.enum) return spec.enum.map(value => JSON.stringify(value)).join(" | ")
  const alternatives = spec.oneOf ?? spec.anyOf
  if (alternatives) return alternatives.map(tsType).join(" | ")
  if (spec.type === "array") return `Array<${tsType(spec.items)}>`
  if (Array.isArray(spec.type)) return spec.type.map(type => tsType({ ...spec, type })).join(" | ")
  if (spec.type === "integer" || spec.type === "number") return "number"
  if (spec.type === "boolean") return "boolean"
  if (spec.type === "null") return "null"
  if (spec.type === "object") {
    const required = new Set(spec.required ?? [])
    const props = Object.entries(spec.properties ?? {}).map(([name, value]) => `${JSON.stringify(name)}${required.has(name) ? "" : "?"}: ${tsType(value)}`)
    return props.length ? `{ ${props.join("; ")} }` : "Record<string, unknown>"
  }
  return "string"
}
function renderDefinitions() {
  let out = "// Generated by scripts/generate-memory-protocol.mjs. Do not edit.\n\n"
  for (const [name, definition] of Object.entries(defs)) {
    if (definition.enum) out += `export type ${name} = ${tsType(definition)}\n\n`
    else if (definition.oneOf || definition.anyOf) out += `export type ${name} = ${tsType(definition)}\n\n`
    else out += `export interface ${name} {\n${Object.entries(definition.properties ?? {}).map(([key, spec]) => `  ${key}${(definition.required ?? []).includes(key) ? "" : "?"}: ${tsType(spec)}`).join("\n")}\n}\n\n`
  }
  out += `export type MemoryCommand = ${Object.keys(memory.commands).map(key => JSON.stringify(key)).join(" | ")}\n`
  out += `export type ProactiveCommand = ${Object.keys(proactive.commands).map(key => JSON.stringify(key)).join(" | ")}\n`
  out += `export const PROACTIVE_LIMITS = Object.freeze(${JSON.stringify(proactive.constants, null, 2)} as const)\n`
  return out
}

fs.writeFileSync(path.join(root, "src/services/agent/memory/protocol.ts"), renderDefinitions())
fs.mkdirSync(path.join(root, "src/services/proactive"), { recursive: true })
fs.writeFileSync(path.join(root, "src/services/proactive/protocol.ts"), `// Generated by scripts/generate-memory-protocol.mjs. Do not edit.\nexport type * from "@/services/agent/memory/protocol"\nexport { PROACTIVE_LIMITS } from "@/services/agent/memory/protocol"\n`)
const rustConstants = Object.entries(proactive.constants).map(([name, value]) => {
  const rustName = name.replace(/[A-Z]/g, letter => `_${letter.toLowerCase()}`).toUpperCase()
  const type = Number.isInteger(value) ? "i64" : "f64"
  return `pub const PROACTIVE_${rustName}: ${type} = ${value};`
}).join("\n")
const rs = `// Generated by scripts/generate-memory-protocol.mjs. Do not edit.\n\npub const MEMORY_COMMANDS: &[&str] = &[${Object.keys(memory.commands).map(JSON.stringify).join(", ")}];\npub const PROACTIVE_COMMANDS: &[&str] = &[${Object.keys(proactive.commands).map(JSON.stringify).join(", ")}];\npub const MEMORY_SCHEMA_VERSION: i64 = ${memory.version};\n${rustConstants}\n`
fs.writeFileSync(path.join(root, "crates/native-host/src/memory/protocol.rs"), rs)

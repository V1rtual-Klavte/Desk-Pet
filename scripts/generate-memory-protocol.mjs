import fs from "node:fs"
import path from "node:path"

const root = path.resolve(import.meta.dirname, "..")
const schema = JSON.parse(fs.readFileSync(path.join(root, "src/services/agent/memory/protocol.json"), "utf8"))
const defs = schema.definitions
const tsType = (v) => {
  if (v.$ref) return v.$ref.split("/").pop()
  if (v.enum) return v.enum.map((value) => JSON.stringify(value)).join(" | ")
  if (v.type === "array") return `Array<${tsType(v.items)}>`
  if (Array.isArray(v.type)) return v.type.includes("integer") || v.type.includes("number") ? "number | null" : "string | null"
  if (v.type === "integer" || v.type === "number") return "number"
  if (v.type === "boolean") return "boolean"
  return "string"
}
const props = (obj) => Object.entries(obj.properties ?? {}).map(([name, spec]) => {
  const optional = !(obj.required ?? []).includes(name)
  return `  ${name}${optional ? "?" : ""}: ${tsType(spec)}`
}).join("\n")
let ts = "// Generated by scripts/generate-memory-protocol.mjs. Do not edit.\n\n"
for (const [name, def] of Object.entries(defs)) {
  if (def.enum) ts += `export type ${name} = ${def.enum.map((value) => JSON.stringify(value)).join(" | ")}\n\n`
  else ts += `export interface ${name} {\n${props(def)}\n}\n\n`
}
ts += `export type MemoryCommand = ${Object.keys(schema.commands).map(k => JSON.stringify(k)).join(" | ")}\n`
fs.writeFileSync(path.join(root, "src/services/agent/memory/protocol.ts"), ts)
let rs = "// Generated by scripts/generate-memory-protocol.mjs. Do not edit.\n\n"
rs += "pub const MEMORY_COMMANDS: &[&str] = &[" + Object.keys(schema.commands).map(k => JSON.stringify(k)).join(", ") + "];\n"
rs += "pub const MEMORY_SCHEMA_VERSION: i64 = 1;\n"
fs.mkdirSync(path.join(root, "src-tauri/src/memory"), { recursive: true })
fs.writeFileSync(path.join(root, "src-tauri/src/memory/protocol.rs"), rs)
